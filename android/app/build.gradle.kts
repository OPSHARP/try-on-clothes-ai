                file("proguard-rules.pro"),
            )
        }
    }

    // CMake native library for XOR-obfuscated API key
    externalNativeBuild {
        cmake {
            path = file("src/main/cpp/CMakeLists.txt")
            version = "3.22.1"
        }
    }
